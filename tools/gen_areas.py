"""Generate the explored-overlay keys for each zone map in the pinned Forever client."""

import argparse
import json
import sys
import urllib.error
from collections import defaultdict
from pathlib import Path

try:
    from tools.forever_tools import wago
    from tools.forever_tools.fsio import atomic_write
except ModuleNotFoundError:
    from forever_tools import wago
    from forever_tools.fsio import atomic_write

BUILD = "1.60.1.70959"
ROOT = Path(__file__).resolve().parent.parent
USER_AGENT = "LedgerForever/1.0"
CACHE = ROOT / "tools" / ".cache"
OUTPUT = ROOT / "Data" / "Areas.lua"
ZONE = 3
SCHEMAS = {
    "UiMap": ("Type",),
    "UiMapXMapArt": ("UiMapID", "UiMapArtID", "PhaseID"),
    "WorldMapOverlay": (
        "UiMapArtID",
        "OffsetX",
        "OffsetY",
        "TextureWidth",
        "TextureHeight",
        "PlayerConditionID",
    ),
}


def db2(name, refresh=False, offline=False):
    columns = ("ID", *SCHEMAS[name])
    return wago.db2_rows(
        name,
        BUILD,
        CACHE,
        user_agent=USER_AGENT,
        refresh=refresh,
        offline=offline,
        timeout=300,
        ints=columns,
        required=columns,
    )


def overlay_key(row):
    return ":".join(str(row[column]) for column in ("OffsetX", "OffsetY", "TextureWidth", "TextureHeight"))


def area_keys(tables):
    """Return each zone UiMap ID's set of drawable exploration overlay keys."""
    zones = {int(row["ID"]) for row in tables["UiMap"] if row["Type"] == ZONE}
    zones_by_art = defaultdict(set)
    for row in tables["UiMapXMapArt"]:
        if row["UiMapID"] in zones and row["PhaseID"] == 0 and row["UiMapArtID"] > 0:
            zones_by_art[row["UiMapArtID"]].add(row["UiMapID"])

    keys = defaultdict(set)
    for row in tables["WorldMapOverlay"]:
        if min(row[column] for column in ("TextureWidth", "TextureHeight")) <= 0:
            continue
        if row["PlayerConditionID"]:
            continue
        key = overlay_key(row)
        for ui_map in zones_by_art[row["UiMapArtID"]]:
            keys[ui_map].add(key)
    return {ui_map: sorted(values) for ui_map, values in sorted(keys.items())}


def render(areas):
    lines = [
        "-- Generated by tools/gen_areas.py: do not edit.",
        f"-- Source: wago.tools UiMap, UiMapXMapArt, and WorldMapOverlay CSV exports at build {BUILD}.",
        "-- Each value is the set of offsetX:offsetY:textureWidth:textureHeight keys returned by",
        "-- C_MapExplorationInfo.GetExploredMapTextures for that zone's current map art.",
        f"-- Pinned client build: {BUILD}.",
        "-- Regenerate: python3 tools/gen_areas.py",
        "local _, ns = ...",
        "-- stylua: ignore",
        "ns.Areas = {",
    ]
    for ui_map, keys in sorted(areas.items()):
        lines.append(f"\t[{ui_map}] = {{")
        lines.extend(f"\t\t[{json.dumps(key)}] = true," for key in keys)
        lines.append("\t},")
    return "\n".join(lines + ["}", ""])


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    group = parser.add_mutually_exclusive_group()
    group.add_argument("--refresh", action="store_true", help="Download the pinned CSVs again")
    group.add_argument("--offline", action="store_true", help="Require cached CSVs")
    args = parser.parse_args()
    tables = {name: db2(name, **vars(args)) for name in SCHEMAS}
    areas = area_keys(tables)
    if not areas:
        raise ValueError("no zone exploration overlays")
    atomic_write(OUTPUT, render(areas).encode())
    print(f"wrote {OUTPUT.relative_to(ROOT)}: {len(areas)} zones")


if __name__ == "__main__":
    try:
        main()
    except (ValueError, KeyError, OSError, urllib.error.URLError) as error:
        sys.exit(f"gen_areas: {error}")
