"""Generate each zone map's faction territory from the pinned Forever client."""

import argparse
import sys
import urllib.error
from pathlib import Path

try:
    from tools.forever_tools import wago
    from tools.forever_tools.fsio import atomic_write
except ModuleNotFoundError:
    from forever_tools import wago
    from forever_tools.fsio import atomic_write

BUILD = "1.60.1.70959"
ROOT = Path(__file__).resolve().parent.parent
USER_AGENT = "LedgerForever/1.0"
CACHE = ROOT / "tools" / ".cache"
OUTPUT = ROOT / "Data" / "Territory.lua"
ZONE = 3


def db2(name, refresh=False, offline=False):
    schemas = {
        "UiMap": ("ID", "Type"),
        "UiMapAssignment": ("ID", "UiMapID", "AreaID", "WMODoodadPlacementID"),
        "AreaTable": ("ID", "FactionGroupMask"),
    }
    columns = schemas[name]
    return wago.db2_rows(
        name,
        BUILD,
        CACHE,
        user_agent=USER_AGENT,
        refresh=refresh,
        offline=offline,
        timeout=300,
        ints=columns,
        required=columns,
    )


def zone_ids(ui_maps):
    return {row["ID"] for row in ui_maps if row["Type"] == ZONE}


def territory(maps, assignments, areas):
    """Map each zone's whole-map assignment to AreaTable.FactionGroupMask."""
    area_of = {}
    for row in assignments:
        ui_map = row["UiMapID"]
        if ui_map in maps and row["WMODoodadPlacementID"] == 0 and ui_map not in area_of:
            area_of[ui_map] = row["AreaID"]
    masks = {row["ID"]: row["FactionGroupMask"] for row in areas}
    return {ui_map: masks[area] for ui_map, area in sorted(area_of.items()) if area in masks}


def render(territories):
    lines = [
        "-- Generated by tools/gen_territory.py: do not edit.",
        f"-- Source: wago.tools UiMap, UiMapAssignment, and AreaTable CSV exports at build {BUILD}.",
        "-- AreaTable.FactionGroupMask: 2 Alliance, 4 Horde, 0 contested, 6 both.",
        f"-- Pinned client build: {BUILD}.",
        "-- Regenerate: python3 tools/gen_territory.py",
        "---@type string, LedgerForeverNamespace",
        "local _, ns = ...",
        "-- stylua: ignore",
        "ns.Data.territory = {",
    ]
    lines.extend(f"\t[{ui_map}] = {mask}," for ui_map, mask in territories.items())
    return "\n".join([*lines, "}", ""])


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    group = parser.add_mutually_exclusive_group()
    group.add_argument("--refresh", action="store_true", help="Download the pinned CSVs again")
    group.add_argument("--offline", action="store_true", help="Require cached CSVs")
    args = parser.parse_args()
    tables = {name: db2(name, **vars(args)) for name in ("UiMap", "UiMapAssignment", "AreaTable")}
    territories = territory(zone_ids(tables["UiMap"]), tables["UiMapAssignment"], tables["AreaTable"])
    if not territories:
        raise ValueError("no zone territories")
    atomic_write(OUTPUT, render(territories).encode())
    print(f"wrote {OUTPUT.relative_to(ROOT)}: {len(territories)} zones")


if __name__ == "__main__":
    try:
        main()
    except (ValueError, KeyError, OSError, urllib.error.URLError) as error:
        sys.exit(f"gen_territory: {error}")
